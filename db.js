"use strict";
// PostgreSQL connection and table setup.
require("./env");
const { Pool, types } = require("pg");

// BIGINT columns hold millisecond timestamps. They are small enough to be plain numbers.
types.setTypeParser(20, (v) => Number(v));

const SSL_MODE = process.env.DATABASE_SSL;
const pool = process.env.DATABASE_URL
  ? new Pool({
      connectionString: process.env.DATABASE_URL,
      max: 10,
      idleTimeoutMillis: 30000,
      connectionTimeoutMillis: 10000,
      // DATABASE_SSL=1 encrypts the connection and checks the server's certificate.
      // DATABASE_SSL=insecure encrypts it without checking (only for hosts with self-signed certificates).
      ssl: SSL_MODE === "1" ? { rejectUnauthorized: true } : SSL_MODE === "insecure" ? { rejectUnauthorized: false } : undefined
    })
  : null;
if (pool) pool.on("error", (e) => console.error("Database connection problem:", e.message));

function needPool() {
  if (!pool) throw new Error("DATABASE_URL is not set. Copy .env.example to .env and fill it in (see README.md).");
  return pool;
}
const query = (text, params) => needPool().query(text, params);

// Runs the steps inside one all-or-nothing transaction. fn receives a client with .query(text, params).
async function tx(fn) {
  const client = await needPool().connect();
  try {
    await client.query("BEGIN");
    const result = await fn(client);
    await client.query("COMMIT");
    return result;
  } catch (e) {
    try { await client.query("ROLLBACK"); } catch (_) { /* connection already gone */ }
    throw e;
  } finally {
    client.release();
  }
}

// Wards and their bed counts.
const WARDS = { General: 12, Maternity: 6, ICU: 4, Pediatrics: 8 };

const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
  username TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  role TEXT NOT NULL CHECK (role IN ('admin','doctor','receptionist','accounts')),
  pwhash TEXT NOT NULL,
  temp BOOLEAN NOT NULL DEFAULT TRUE,
  last_login BIGINT,
  created BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS sessions (
  id_hash TEXT PRIMARY KEY,
  username TEXT NOT NULL REFERENCES users(username) ON DELETE CASCADE,
  created BIGINT NOT NULL,
  last_seen BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_by_user ON sessions(username);
CREATE TABLE IF NOT EXISTS doctors (
  id TEXT PRIMARY KEY,
  name TEXT NOT NULL,
  dept TEXT NOT NULL,
  room TEXT NOT NULL,
  fee INTEGER NOT NULL,
  duty BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE IF NOT EXISTS patients (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  age INTEGER NOT NULL CHECK (age BETWEEN 0 AND 120),
  sex TEXT NOT NULL CHECK (sex IN ('F','M')),
  phone TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL CHECK (status IN ('Admitted','Outpatient','Discharged')),
  ward TEXT NOT NULL DEFAULT '',
  bed INTEGER NOT NULL DEFAULT 0,
  doctor_id TEXT NOT NULL REFERENCES doctors(id),
  dx TEXT NOT NULL DEFAULT '',
  since TEXT NOT NULL CHECK (since ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$')
);
CREATE UNIQUE INDEX IF NOT EXISTS one_patient_per_bed ON patients(ward, bed) WHERE status = 'Admitted';
CREATE TABLE IF NOT EXISTS appointments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id INTEGER NOT NULL REFERENCES patients(id),
  doctor_id TEXT NOT NULL REFERENCES doctors(id),
  date TEXT NOT NULL CHECK (date ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  time TEXT NOT NULL CHECK (time ~ '^[0-2][0-9]:[0-5][0-9]$'),
  reason TEXT NOT NULL,
  status TEXT NOT NULL CHECK (status IN ('Scheduled','Checked in','Completed','Cancelled'))
);
CREATE UNIQUE INDEX IF NOT EXISTS one_appointment_per_slot ON appointments(doctor_id, date, time) WHERE status <> 'Cancelled';
CREATE INDEX IF NOT EXISTS appointments_by_patient ON appointments(patient_id);
CREATE TABLE IF NOT EXISTS invoices (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  patient_id INTEGER NOT NULL REFERENCES patients(id),
  descr TEXT NOT NULL,
  amount INTEGER NOT NULL CHECK (amount > 0),
  due TEXT NOT NULL CHECK (due ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$'),
  paid BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS invoices_by_patient ON invoices(patient_id);
CREATE TABLE IF NOT EXISTS audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  t BIGINT NOT NULL,
  username TEXT NOT NULL,
  ip TEXT,
  msg TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS meta (k TEXT PRIMARY KEY, v TEXT NOT NULL);
`;

// Creates the tables if they are missing. Safe to run every time the server starts.
async function init() {
  await tx(async (c) => {
    await c.query("SELECT pg_advisory_xact_lock(7000)"); // two servers starting together must not both create tables
    await c.query(SCHEMA);
  });
}

// After rows are inserted with fixed ids, make the counters carry on after the highest one.
async function syncCounters(c) {
  for (const t of ["patients", "appointments", "invoices", "audit"]) {
    await c.query("SELECT setval(pg_get_serial_sequence('" + t + "', 'id'), COALESCE((SELECT MAX(id) FROM " + t + "), 0) + 1, false)");
  }
}

async function close() { if (pool) await pool.end(); }

module.exports = { query, tx, init, close, syncCounters, WARDS };
